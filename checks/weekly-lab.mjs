import assert from 'node:assert/strict';
import {weeklyFixture,prepareFixture} from '../scripts/weekly-review-fixture.mjs';
import {renderReport,runLive} from '../scripts/weekly-review-lab.mjs';
import {trainingCalendar,phaseCalendar} from '../server/api.js';
import {easyWorkouts} from './workout-fixtures.mjs';

const fixture=weeklyFixture('2026-11-03'),prepared=prepareFixture(fixture);
assert.equal(prepared.prepared.profile.review.decision,'hold');
assert.equal(prepareFixture(weeklyFixture('2026-11-03','reduce')).prepared.profile.review.maxWeeklyKm,12);
assert.match(prepareFixture(weeklyFixture('2026-11-03','pain')).preflightError,/dor/);
const env={GEMINI_MODEL:'gemini-test',GEMINI_API_KEY:'never-print-this-secret'};
let calls=0;
const blocked=await runLive(weeklyFixture('2026-11-03','pain'),env,async()=>{calls++;throw Error('Unexpected provider call');});
assert.equal(blocked.status,'blocked');assert.equal(calls,0);
const profile=prepared.prepared.profile;
const raw=easyWorkouts({summary:'Cenário fictício.',feasibility:'Manter conforme recuperação.',warnings:['Revisar semanalmente.'],phases:phaseCalendar(profile).map(()=>({title:'Preparação',focus:'Continuidade.'})),weeks:trainingCalendar(profile).map(w=>({start:w.start,focus:'Manutenção.',totalKm:99,sessions:w.availableDates.map(date=>({date,title:'Rodagem',km:5,minutes:35,rpe:3,long:false,instructions:'Conversa confortável.'}))}))});
const report=await runLive(fixture,env,async(url,options)=>{calls++;assert.equal(options.headers['x-goog-api-key'],env.GEMINI_API_KEY);return Response.json({candidates:[{finishReason:'STOP',content:{parts:[{text:JSON.stringify(raw)}]}}]});});
assert.equal(report.status,'completed');assert.equal(calls,1);assert.equal(report.providerCalls,1);
assert.equal(report.result.plan.weeks[0].totalKm,15);assert.ok(report.rawResponse);
assert.ok(!JSON.stringify(report).includes(env.GEMINI_API_KEY));
const failed=await runLive(fixture,env,async()=>Response.json({candidates:[{finishReason:'STOP',content:{parts:[{text:'{}'}]}}]}));
assert.equal(failed.status,'failed');assert.ok(failed.rawResponse);assert.match(failed.error,/validar/);
const hostile={...report,job:{status:'failed',error:'</script><img src=x onerror=alert(1)>'}};
const html=renderReport(hostile);
assert.ok(!html.includes('</script><img'));assert.ok(html.includes('&lt;/script&gt;'));
const embedded=html.match(/<script type="application\/json" id="report">([\s\S]*?)<\/script>/)[1];
assert.equal(JSON.parse(embedded).job.error,hostile.job.error);
assert.match(html,/Baixar relatório JSON/);
console.log('PASS: laboratório fictício, manutenção/redução/dor, chamada única, captura antes da validação, segredo ausente e relatório visual com JSON seguro.');
